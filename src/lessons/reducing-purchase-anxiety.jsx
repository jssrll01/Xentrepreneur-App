      <ul>
        <li>Conversion rate — purchase completion</li>
        <li>Trial conversion — trial → paid</li>
        <li>Refund rate — purchases → refunds</li>
        <li>Cancellation rate — customers → cancellations</li>
        <li>Support contact rate — customers needing assistance</li>
        <li>First response time — support responsiveness</li>
        <li>Resolution time — speed of problem resolution</li>
        <li>Activation rate — customers reaching meaningful value</li>
        <li>Warranty claim rate — qualifying product problems</li>
        <li>Checkout abandonment — customers leaving before purchase</li>
        <li>CSAT — customer satisfaction</li>
        <li>Repeat purchase rate — returning customers</li>
        <li>Retention rate — customers remaining over time</li>
      </ul>

