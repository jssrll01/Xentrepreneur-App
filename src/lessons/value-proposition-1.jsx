import LessonLayout from '../components/LessonLayout'

export default function ValueProposition1() {
  return (
    <LessonLayout
      number="125"
      title="Value Proposition — Part 1"
      summary="20 core value drivers — lower price, quality, speed, convenience, reliability, performance, ease of use, time and cost savings, risk reduction, personalization, customization, accessibility, availability, simplicity, transparency, security, privacy, and expertise."
    >
      <h2>Value Proposition — Part 1</h2>

      <h2>1. Value Proposition</h2>
      <h3>Definition</h3>
      <p>A value proposition explains why a specific customer should choose a product, service, or business instead of available alternatives.</p>
      <p>It answers four fundamental questions: Who is the customer? What problem or need do they have? What value does the business provide? Why should they choose this solution?</p>
      <p>A value proposition is not simply a slogan. A strong value proposition should be relevant, understandable, credible, and meaningful to the target customer.</p>

      <hr />

      <h2>2. Lower Price</h2>
      <h3>Definition</h3>
      <p>A lower-price value proposition emphasizes offering a comparable or suitable solution at a lower price than relevant alternatives. The objective is not necessarily to be the cheapest business in the market. It is to make the customer's purchase more affordable while maintaining sustainable economics.</p>

      <h3>Formula</h3>
      <p><strong>Gross Profit = Selling Price − COGS</strong></p>
      <p><strong>Gross Margin = (Gross Profit ÷ Selling Price) × 100</strong></p>

      <h3>Risks</h3>
      <p>Price wars, low margins, perception of lower quality, difficulty funding customer support, dependence on high sales volume.</p>

      <h3>Principle</h3>
      <p>Lower price should come from a sustainable cost structure, not from permanently destroying margins.</p>

      <hr />

      <h2>3. Higher Quality</h2>
      <h3>Definition</h3>
      <p>A higher-quality value proposition emphasizes superior quality, durability, accuracy, craftsmanship, materials, consistency, or overall product/service standards. Quality must be defined relative to customer requirements.</p>

      <h3>Quality Dimensions</h3>
      <p>Durability, accuracy, reliability, materials, manufacturing consistency, performance, design, customer support, documentation, quality control.</p>

      <h3>Metrics</h3>
      <p>Defect rate, return rate, warranty claims, customer complaints, first-pass yield, product failure rate, customer satisfaction.</p>

      <h3>Risk</h3>
      <p>Claiming "high quality" without measurable evidence can weaken credibility.</p>

      <hr />

      <h2>4. Faster Service</h2>
      <h3>Definition</h3>
      <p>A faster-service value proposition emphasizes shorter delivery, response, processing, production, or completion times. Customers often value speed because delays create costs or inconvenience.</p>

      <h3>Metrics</h3>
      <p>Average service time, median service time, on-time completion rate, response time.</p>

      <h3>Principle</h3>
      <p>Never promise speed that your operation cannot reliably deliver.</p>

      <hr />

      <h2>5. Better Convenience</h2>
      <h3>Definition</h3>
      <p>A convenience value proposition reduces the effort customers must spend to discover, purchase, receive, use, maintain, or return a product or service.</p>
      <p>Convenience can mean easy ordering, easy payment, home delivery, pickup, simple onboarding, easy returns, multiple payment methods, self-service, automatic renewal, or centralized service.</p>

      <h3>Metrics</h3>
      <p>Checkout completion, time to purchase, cart abandonment, customer effort, support requests, repeat purchase.</p>

      <h3>Principle</h3>
      <p>Convenience is the reduction of unnecessary customer effort.</p>

      <hr />

      <h2>6. Greater Reliability</h2>
      <h3>Definition</h3>
      <p>A reliability value proposition emphasizes consistent performance and dependable delivery over time. Reliability can apply to product functionality, delivery, service availability, customer support, order accuracy, system uptime, and supplier performance.</p>

      <h3>Metrics</h3>
      <p>Uptime, failure rate, on-time delivery, order accuracy, defect rate, mean time to recovery, supplier on-time delivery.</p>

      <h3>Reliability vs Quality</h3>
      <p>Quality concerns whether the product meets the required standard. Reliability concerns whether it continues to perform consistently. A product can initially be high quality but poorly reliable if it frequently fails.</p>

      <hr />

      <h2>7. Better Performance</h2>
      <h3>Definition</h3>
      <p>A performance value proposition promises or demonstrates better measurable results from the product or service. Performance may involve speed, output, accuracy, capacity, efficiency, conversion, battery life, processing power, or productivity.</p>

      <h3>Metrics</h3>
      <p>Processing time, output/hour, accuracy, conversion rate, response time, productivity, error rate.</p>

      <h3>Important Principle</h3>
      <p>Performance claims should be specific and measurable whenever practical.</p>

      <hr />

      <h2>8. Easier Operation</h2>
      <h3>Definition</h3>
      <p>An ease-of-use value proposition reduces the difficulty customers experience when learning, operating, configuring, or maintaining a product.</p>

      <h3>Metrics</h3>
      <p>Task completion rate, time to complete task, error rate, support requests, onboarding completion, user satisfaction.</p>

      <h3>Principle</h3>
      <p>Ease of use is measured by what customers can accomplish, not merely by how attractive the interface looks.</p>

      <hr />

      <h2>9. Time Savings</h2>
      <h3>Definition</h3>
      <p>A time-saving value proposition helps customers accomplish an objective in less time. Time can be valuable because it can be redirected toward work, family, customers, education, leisure, or higher-value activities.</p>

      <h3>Economic Value</h3>
      <p><strong>Time Value = Hours Saved × Relevant Value per Hour</strong></p>
      <p>If 130 hours are saved and relevant employee time is valued at ₱300/hour: 130 × ₱300 = ₱39,000. This is not automatically cash profit; it represents an estimated economic value that depends on how the saved capacity is used.</p>

      <hr />

      <h2>10. Cost Savings</h2>
      <h3>Definition</h3>
      <p>A cost-saving value proposition reduces the customer's total cost of achieving a particular outcome. The relevant comparison is usually total cost, not merely purchase price.</p>

      <h3>Total Cost of Ownership</h3>
      <p>Consider: purchase + installation + training + maintenance + labor + energy + repairs + switching costs.</p>

      <h3>Principle</h3>
      <p>Cost savings should be calculated against the customer's real alternative.</p>

      <hr />

      <h2>11. Risk Reduction</h2>
      <h3>Definition</h3>
      <p>A risk-reduction value proposition lowers the likelihood or potential impact of undesirable outcomes. Customers may worry about financial loss, product failure, security incidents, delays, compliance problems, poor quality, operational disruption, or incorrect decisions.</p>
      <p>Examples: warranty, backup system, insurance, security monitoring, quality testing, professional certification, clear refund policy, technical support, redundant infrastructure.</p>

      <h3>Principle</h3>
      <p>A business should explain how its product reduces risk rather than simply claiming that it is "safe" or "secure."</p>

      <hr />

      <h2>12. Personalized Service</h2>
      <h3>Definition</h3>
      <p>Personalized service adapts interactions, recommendations, communication, or service delivery to individual customer circumstances.</p>
      <p>Examples: personalized recommendations, customer-specific onboarding, individual account management, customized follow-up, purchase-history-based suggestions, personalized service plans.</p>

      <h3>Benefits</h3>
      <p>Greater relevance, better customer experience, potentially higher conversion, stronger retention, better customer relationships.</p>

      <h3>Risks</h3>
      <p>Privacy concerns, incorrect personalization, excessive messaging, data quality problems.</p>

      <h3>Principle</h3>
      <p>Useful personalization should feel relevant, not intrusive.</p>

      <hr />

      <h2>13. Customization</h2>
      <h3>Definition</h3>
      <p>Customization allows customers to modify a product, service, package, configuration, or experience according to their requirements.</p>

      <h3>Pricing Formula</h3>
      <p><strong>Final Price = Base Price + Selected Options + Customization Cost + Additional Service Costs</strong></p>

      <h3>Risks</h3>
      <p>Scope creep, higher production costs, longer delivery, configuration errors, difficult forecasting.</p>

      <h3>Principle</h3>
      <p>Customization should be controlled rather than unlimited.</p>

      <hr />

      <h2>14. Accessibility</h2>
      <h3>Definition</h3>
      <p>An accessibility value proposition makes products, services, information, or experiences easier for a broader range of people to access and use. Accessibility can involve physical access, digital accessibility, language, affordability, payment access, geographic availability, assistive technologies, and easy-to-understand information.</p>

      <h3>Business Value</h3>
      <p>Accessibility can expand the addressable market, improve usability, reduce barriers, improve customer experience, and support inclusive design.</p>

      <h3>Principle</h3>
      <p>Accessibility should be designed into the product rather than treated only as an afterthought.</p>

      <hr />

      <h2>15. Availability</h2>
      <h3>Definition</h3>
      <p>An availability value proposition emphasizes that customers can obtain a product or service when and where they need it. Availability can involve inventory availability, 24/7 digital access, geographic coverage, delivery availability, appointment availability, and multiple sales channels.</p>

      <h3>Metrics</h3>
      <p>In-stock rate, stockout rate, service availability, appointment fill rate, geographic coverage, uptime.</p>

      <h3>Principle</h3>
      <p>Availability requires capacity and inventory planning. Promising constant availability without sufficient supply creates customer disappointment.</p>

      <hr />

      <h2>16. Simplicity</h2>
      <h3>Definition</h3>
      <p>A simplicity value proposition reduces unnecessary complexity in purchasing, understanding, configuring, or using a product.</p>

      <h3>Simplicity Can Apply To</h3>
      <p>Pricing, product selection, checkout, user interface, setup, documentation, contracts, communication, customer support.</p>

      <h3>Principle</h3>
      <p>Simplicity means reducing unnecessary complexity, not removing useful functionality.</p>

      <hr />

      <h2>17. Transparency</h2>
      <h3>Definition</h3>
      <p>A transparency value proposition provides customers with clear and understandable information about relevant prices, features, limitations, policies, processes, and conditions.</p>
      <p>Transparent businesses clearly communicate price, fees, features, delivery time, refund rules, warranty, contract terms, limitations, and eligibility requirements.</p>

      <h3>Benefits</h3>
      <p>Reduces uncertainty, builds trust, reduces misunderstandings, helps customers compare alternatives, reduces support disputes.</p>

      <h3>Principle</h3>
      <p>Transparency means making decision-relevant information understandable before the customer commits.</p>

      <hr />

      <h2>18. Security</h2>
      <h3>Definition</h3>
      <p>A security value proposition emphasizes protection against unauthorized access, misuse, fraud, attacks, loss, or disruption. For digital businesses, security may include authentication, authorization, encryption, secure payment processing, monitoring, backups, access controls, vulnerability management, and incident response.</p>

      <h3>Important Security Principle</h3>
      <p>Do not simply say "100% secure." Security is a risk-management discipline, not an absolute guarantee. Better communication describes concrete controls.</p>

      <hr />

      <h2>19. Privacy</h2>
      <h3>Definition</h3>
      <p>A privacy value proposition focuses on responsible handling of personal information and giving customers appropriate control, clarity, and protection concerning their data.</p>

      <h3>Privacy vs Security</h3>
      <p>Privacy concerns appropriate handling and use of information. Security concerns protection against unauthorized access, loss, alteration, or disruption. They overlap but are not identical. A business can have strong security controls while still having poor privacy practices.</p>

      <hr />

      <h2>20. Expertise</h2>
      <h3>Definition</h3>
      <p>An expertise value proposition emphasizes specialized knowledge, experience, skills, judgment, or capability that helps customers solve problems they cannot easily solve themselves.</p>

      <h3>Example</h3>
      <p>A web developer does not merely sell "HTML/CSS/React coding." The customer may actually value a professional online presence, faster development, better usability, technical problem solving, mobile responsiveness, and maintainability. Therefore technical capability → customer outcome is stronger than simply listing technical skills.</p>

      <h3>Principle</h3>
      <p>Expertise becomes valuable when it produces useful outcomes for the customer.</p>

      <hr />

      <h2>Value Proposition Categories</h2>
      <ul>
        <li>Economic value — lower price, cost savings</li>
        <li>Quality value — higher quality, better performance</li>
        <li>Speed value — faster service, time savings</li>
        <li>Convenience value — better convenience, easier operation, simplicity</li>
        <li>Reliability value — greater reliability, availability</li>
        <li>Risk value — risk reduction, security</li>
        <li>Personal value — personalized service, customization</li>
        <li>Access value — accessibility, availability</li>
        <li>Trust value — transparency, privacy, security</li>
        <li>Expertise value — expertise</li>
      </ul>
      <p>A single product can provide several simultaneously.</p>

      <hr />

      <h2>Value Proposition vs Feature vs Benefit vs Outcome</h2>
      <p>Feature — what the product has (e.g., "the platform includes automated backups"). Benefit — what the feature helps the customer do (e.g., "your data can be restored more easily after a problem"). Outcome — what ultimately matters to the customer (e.g., "you can reduce disruption when data is accidentally lost"). Value proposition — the broader reason to choose the solution (e.g., "keep your business information protected and recoverable without manually managing backups").</p>

      <hr />

      <h2>Key Principles</h2>
      <ol>
        <li>A value proposition explains the meaningful value a customer receives from choosing a solution.</li>
        <li>Lower price is valuable only when the business can sustain the economics.</li>
        <li>Higher quality should be supported by actual product or service standards.</li>
        <li>Faster service requires operational capacity capable of consistently meeting the promised timeframe.</li>
        <li>Convenience reduces unnecessary customer effort.</li>
        <li>Reliability means consistent performance or delivery over time.</li>
        <li>Performance value should be connected to measurable customer outcomes.</li>
        <li>Ease of operation reduces the knowledge and effort required to accomplish a task.</li>
        <li>Time savings can have substantial economic value when customers can redirect saved time toward valuable activities.</li>
        <li>Cost savings should consider the customer's total relevant cost, not only purchase price.</li>
        <li>Risk reduction should explain the specific mechanism by which risk is reduced.</li>
        <li>Personalization should improve relevance without becoming unnecessarily intrusive.</li>
        <li>Customization creates value by allowing customers to adapt an offer to their requirements, but excessive customization increases complexity.</li>
        <li>Accessibility expands the ability of different customers to use or obtain products and services.</li>
        <li>Availability depends on adequate inventory, capacity, infrastructure, or service coverage.</li>
        <li>Simplicity removes unnecessary complexity without eliminating valuable functionality.</li>
        <li>Transparency reduces uncertainty by clearly communicating decision-relevant information.</li>
        <li>Security protects systems, information, transactions, and operations against relevant threats.</li>
        <li>Privacy concerns appropriate collection, use, retention, sharing, and protection of personal information.</li>
        <li>Expertise creates value when specialized knowledge produces useful customer outcomes.</li>
        <li>Features are not the same as benefits, and benefits are not always the same as customer outcomes.</li>
        <li>A business can combine several value propositions, but a clear primary value proposition usually makes communication easier.</li>
        <li>Every value proposition has an operational and financial cost.</li>
        <li>A value proposition should be credible; unsupported claims weaken trust.</li>
        <li>The strongest value propositions connect a specific customer problem to a specific desired outcome and a clearly communicated reason to choose the solution.</li>
      </ol>

      <h3>Core Formula</h3>
      <p>
        Target Customer → Customer Problem → Customer Need → Desired Outcome → Value Driver →
        Product / Service → Differentiation → Evidence → Clear Communication → Purchase → Value
        Delivery → Customer Outcome → Satisfaction → Retention → Advocacy → Measurement →
        Optimization.
      </p>
    </LessonLayout>
  )
}
