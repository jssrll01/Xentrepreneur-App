import LessonLayout from '../components/LessonLayout'

export default function Affiliate1() {
  return (
    <LessonLayout
      number="269"
      title="Affiliate — Part 1"
      summary="Affiliate marketing fundamentals explained — programs, networks, partners, links, codes, and commission models."
    >
      <h2>Affiliate — Part 1</h2>
      <p>Affiliate marketing is a performance-based channel where third parties promote your product and earn a commission per qualifying action. It is scalable because cost is tied to results.</p>

      <h2>1. Affiliate Marketing</h2>
      <p><strong>What it is:</strong> A distribution model where affiliates earn commission on sales or leads they generate.</p>
      <p><strong>How it works:</strong> Affiliate shares a tracked link; a customer clicks, converts, and the affiliate is credited.</p>
      <p><strong>How to do it:</strong> Define offer, commission structure, tracking, and rules; recruit affiliates; optimize.</p>

      <h2>2. Affiliate Program</h2>
      <p><strong>What it is:</strong> The formal program that manages affiliate relationships.</p>
      <p><strong>How to do it:</strong> Program terms, tracking platform, marketing assets, payout process.</p>

      <h2>3. Affiliate Network</h2>
      <p><strong>What it is:</strong> A third-party platform connecting merchants and affiliates (e.g., ShareASale, CJ).</p>
      <p><strong>Use when:</strong> You want reach without managing affiliates directly.</p>

      <h2>4. Affiliate Partner</h2>
      <p><strong>What it is:</strong> The person or business promoting your offer.</p>
      <p><strong>How to do it:</strong> Recruit for fit; onboard; support; monitor performance.</p>

      <h2>5. Affiliate Link</h2>
      <p><strong>What it is:</strong> A URL that tracks who referred a visitor.</p>
      <p><strong>How to do it:</strong> Use your affiliate platform to generate unique links per affiliate.</p>

      <h2>6. Affiliate Code</h2>
      <p><strong>What it is:</strong> A coupon or promo code tied to an affiliate.</p>
      <p><strong>How to do it:</strong> Generate codes; track redemption; reconcile with link-based tracking.</p>

      <h2>7. Affiliate Commission</h2>
      <p><strong>What it is:</strong> The payment an affiliate earns.</p>
      <p><strong>How to do it:</strong> Set rates that are competitive but still leave positive unit economics.</p>

      <h2>8. CPA Commission</h2>
      <p><strong>What it is:</strong> Cost Per Acquisition — fixed fee per action.</p>
      <p><strong>Use when:</strong> You want predictable acquisition cost.</p>

      <h2>9. CPC Commission</h2>
      <p><strong>What it is:</strong> Cost Per Click — payment per click.</p>
      <p><strong>Use when:</strong> Traffic is the primary value, though conversion is not guaranteed.</p>

      <h2>10. Revenue-Share Commission</h2>
      <p><strong>What it is:</strong> Affiliate earns a percentage of revenue generated.</p>
      <p><strong>Use when:</strong> Revenue is variable and you want aligned incentives.</p>

      <h2>11. Lead Commission</h2>
      <p><strong>What it is:</strong> Payment per qualified lead.</p>
      <p><strong>Use when:</strong> The sale cycle is long and leads are valuable.</p>

      <h2>12. Sale Commission</h2>
      <p><strong>What it is:</strong> Payment per completed sale.</p>
      <p><strong>Use when:</strong> Closing is what matters most.</p>

      <h2>13. Referral Commission</h2>
      <p><strong>What it is:</strong> Payment for referring a customer, regardless of channel.</p>
      <p><strong>Use when:</strong> Referrals are broad and hard to attribute precisely.</p>

      <h2>14. Recurring Commission</h2>
      <p><strong>What it is:</strong> Payment every billing period for a subscription the affiliate referred.</p>
      <p><strong>Use when:</strong> You have subscription revenue and want affiliates to support retention.</p>

      <h2>15. Lifetime Commission</h2>
      <p><strong>What it is:</strong> Payment for the entire lifetime of the customer.</p>
      <p><strong>Use when:</strong> The affiliate relationship is deep and long-term.</p>
    </LessonLayout>
  )
}
