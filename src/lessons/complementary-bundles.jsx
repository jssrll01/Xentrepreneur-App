      <ul>
        <li>Product + accessory — physical/digital accessory — better usability</li>
        <li>Product + maintenance — maintenance service — longer/better operation</li>
        <li>Product + support — assistance — lower uncertainty</li>
        <li>Product + training — education — better adoption</li>
        <li>Product + installation — setup labor — ready-to-use solution</li>
        <li>Product + delivery — logistics — convenience</li>
        <li>Product + warranty — product protection — reduced perceived risk</li>
        <li>Product + customization — personalization — individual fit</li>
        <li>Product + consultation — expert guidance — better decision</li>
        <li>Product + digital resource — digital knowledge/tools — education and convenience</li>
      </ul>

